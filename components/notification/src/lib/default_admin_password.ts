import crypto from 'node:crypto';

// SHA-256 of the admin password the config templates and Helm chart used to ship. Only the hash is kept, so the
// default itself is not in the code base.
const SHIPPED_DEFAULT_ADMIN_PASSWORD_SHA256 = 'c3c9a0a7ed83ee612c4a3d0501c042778aed5d6399753d7d94ef9ba87c15de1c';

/**
 * Whether the configured admin password equals the publicly known shipped default.
 * @param {unknown} password Configured `adminConfig.password`.
 * @returns {boolean}
 */
export function isShippedDefaultAdminPassword(password: unknown): boolean {
  if (typeof password !== 'string' || !password) return false;
  const hash = Buffer.from(crypto.createHash('sha256').update(password).digest('hex'));
  return crypto.timingSafeEqual(hash, Buffer.from(SHIPPED_DEFAULT_ADMIN_PASSWORD_SHA256));
}

/**
 * Warn at startup when the admin password is still the shipped default.
 *
 * It only warns and never refuses to start: installs created from earlier templates still carry this password in
 * their config, and an upgrade must not lock the operator out or crash the service. A correctly configured install
 * (generated by init.sh or the Helm init-secrets hook, or set by the operator) never trips it.
 * @param {any} conf Component config.
 * @param {{ save: Function }} log Logger.
 * @returns {boolean} True when the default is in use.
 */
export function warnOnDefaultAdminPassword(conf: any, log: { save: (type: string, data: any, level?: string) => unknown }): boolean {
  if (!isShippedDefaultAdminPassword(conf?.adminConfig?.password)) return false;
  log.save(
    'admin-default-password-warning',
    {
      message:
        'adminConfig.password is the publicly known shipped default, so anyone can log in to the notification admin panel. ' +
        'Set a new random adminConfig.password (config.json, or the Secret for Helm) and restart; it also signs admin Digest nonces.',
      production: conf?.default_env === 'production' || process.env.NODE_ENV === 'production',
    },
    'warn',
  );
  return true;
}
